const fs = require('fs');
const path = require('path');
const { ROOT, TESTS_DIR } = require('../repoConfig');

/** Resolve fixtures whether keyed by full repo path or repo-relative path. */
function lookupCases(fixtures, groupKey) {
  if (fixtures.cases[groupKey]) return fixtures.cases[groupKey];
  const relative = groupKey.replace(/^[^/]+\//, '');
  if (fixtures.cases[relative]) return fixtures.cases[relative];
  for (const [key, value] of Object.entries(fixtures.cases)) {
    if (key.replace(/^[^/]+\//, '') === relative) return value;
  }
  return null;
}

/** Group manifest call sites into exported functions (drop module-level entries). */
function groupByFunction(manifest) {
  const groups = new Map();
  for (const usage of manifest) {
    if (!usage.surroundingFunction || usage.surroundingFunction.startsWith('<')) {
      continue;
    }
    const key = usage.file + '::' + usage.surroundingFunction;
    if (!groups.has(key)) {
      groups.set(key, {
        key,
        file: usage.file,
        fn: usage.surroundingFunction,
        classifications: new Set(),
        lines: new Set(),
      });
    }
    const g = groups.get(key);
    g.classifications.add(usage.classification);
    g.lines.add(usage.line);
  }
  return Array.from(groups.values());
}

function importPathFor(sourceFile) {
  const absTarget = path.join(ROOT, sourceFile);
  let rel = path.relative(TESTS_DIR, absTarget).split(path.sep).join('/');
  rel = rel.replace(/\.js$/, '');
  return rel.startsWith('.') ? rel : './' + rel;
}

function testFileName(sourceFile, fn) {
  const base = path.basename(sourceFile, '.js');
  return base + '.' + fn + '.test.js';
}

function renderTest(group, cases, clockIso) {
  const importPath = importPathFor(group.file);
  const classifications = Array.from(group.classifications).sort();
  const lines = Array.from(group.lines).sort((a, b) => a - b);

  return `// AUTO-GENERATED by pipeline/characterize — do not edit by hand.
// Characterization baseline for ${group.file} :: ${group.fn}()
// Classifications: ${classifications.join(', ')}
// Covers moment call sites at line(s): ${lines.join(', ')}
const target = require('${importPath}');

const FIXED_NOW = new Date('${clockIso}');
const CASES = ${JSON.stringify(cases, null, 2)};

function invoke(args) {
  try {
    return { ok: target.${group.fn}(...args) };
  } catch (err) {
    return { error: { name: err.name, message: err.message } };
  }
}

describe('${group.fn} [${classifications.join(', ')}]', () => {
  beforeAll(() => {
    jest.useFakeTimers({ now: FIXED_NOW });
  });
  afterAll(() => {
    jest.useRealTimers();
  });

  test.each(CASES.map((args, i) => [i, args]))(
    'case %s -> %j',
    (i, args) => {
      expect(invoke(args)).toMatchSnapshot();
    }
  );
});
`;
}

/**
 * Generate one snapshot test per exported function that has moment call sites.
 * Returns metadata for the summary artifact. Throws if a discovered function
 * lacks representative inputs (no silent gaps).
 */
function generate(manifest, fixtures) {
  fs.mkdirSync(TESTS_DIR, { recursive: true });

  const groups = groupByFunction(manifest);
  const wanted = new Set();
  const results = [];
  const missing = [];

  for (const group of groups) {
    const cases = lookupCases(fixtures, group.key);
    if (!cases) {
      missing.push(group.key);
      continue;
    }
    const fileName = testFileName(group.file, group.fn);
    const content = renderTest(group, cases, fixtures.clock);
    fs.writeFileSync(path.join(TESTS_DIR, fileName), content, 'utf8');
    wanted.add(fileName);

    results.push({
      file: group.file,
      function: group.fn,
      classifications: Array.from(group.classifications).sort(),
      coveredLines: Array.from(group.lines).sort((a, b) => a - b),
      testFile: path
        .relative(ROOT, path.join(TESTS_DIR, fileName))
        .split(path.sep)
        .join('/'),
      caseCount: cases.length,
    });
  }

  if (missing.length) {
    throw new Error(
      'No fixtures for discovered function(s): ' + missing.join(', ')
    );
  }

  pruneStaleTests(wanted);
  return results;
}

/** Remove previously generated *.test.js files no longer produced. */
function pruneStaleTests(wanted) {
  for (const entry of fs.readdirSync(TESTS_DIR)) {
    if (entry.endsWith('.test.js') && !wanted.has(entry)) {
      fs.unlinkSync(path.join(TESTS_DIR, entry));
    }
  }
}

module.exports = { generate, TESTS_DIR };
